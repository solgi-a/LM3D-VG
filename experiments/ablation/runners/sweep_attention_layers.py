
import json
import os
import subprocess
import sys
import time


RUN = True
SELF_TEST = False

ARMS = [
    (1, None),
    (2, None),
    (3, None),
    (4, None),
]

FUSION_HEADS = None
PARSING_FOLDER = "final_parsing_tokenized"
USE_CACHED_SCENES = True
CACHED_SCENES_ROOT = "cached_scenes"
SEED = 42
EPOCH = 50
BATCH_SIZE = 8
EXTRA_ARGS = ["--use_color", "--use_normal"]
RUN_EVAL = True
STOP_ON_FAILURE = True
OUT_ROOT = os.path.join("outputs", "ablation", "attention_layer_sweep")


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))

LAUNCHER_TEMPLATE = '''"""Auto-generated by experiments/ablation/runners/sweep_attention_layers.py -- do not edit.

Arm: fusion_depth={fusion_depth!r}  dec_layers={dec_layers!r}  heads={heads!r}

Patches the two attention-stack sizes that models/refnet.py hard-codes, then runs the
unmodified scripts/ScanRefer_train.py. Kept on disk as the record of this arm.
"""

import os
import runpy
import sys

REPO_ROOT = {repo!r}
sys.path.insert(0, REPO_ROOT)
os.chdir(REPO_ROOT)

FUSION_DEPTH = {fusion_depth!r}
FUSION_HEADS = {heads!r}
DEC_LAYERS = {dec_layers!r}

# ---- fusion self-attention stack (MatchModule depth) ---------------------------------
if FUSION_DEPTH is not None or FUSION_HEADS is not None:
    import models.match_module as match_module

    _original_match_init = match_module.MatchModule.__init__

    def _patched_match_init(self, args, num_proposals=256, hidden_size=128,
                            det_channel=288, head=4, depth=3):
        if FUSION_HEADS is not None:
            head = FUSION_HEADS
        if FUSION_DEPTH is not None:
            depth = FUSION_DEPTH
        print(f"[sweep] MatchModule(head={{head}}, depth={{depth}})", flush=True)
        return _original_match_init(self, args, num_proposals=num_proposals,
                                    hidden_size=hidden_size, det_channel=det_channel,
                                    head=head, depth=depth)

    match_module.MatchModule.__init__ = _patched_match_init

# ---- proposal decoder (config_transformer is a local dict inside RefNet.__init__, so
#      it is intercepted where it arrives instead) --------------------------------------
if DEC_LAYERS is not None:
    import models.proposal_module as proposal_module

    _original_proposal_init = proposal_module.ProposalModule.__init__

    def _patched_proposal_init(self, *args, **kwargs):
        config = kwargs.get("config_transformer")
        if isinstance(config, dict):
            config = dict(config)
            config["dec_layers"] = DEC_LAYERS
            kwargs["config_transformer"] = config
            print(f"[sweep] ProposalModule(dec_layers={{DEC_LAYERS}})", flush=True)
        return _original_proposal_init(self, *args, **kwargs)

    proposal_module.ProposalModule.__init__ = _patched_proposal_init

sys.argv = {argv!r}
runpy.run_path(os.path.join(REPO_ROOT, "scripts", "ScanRefer_train.py"),
               run_name="__main__")
'''


def arm_name(fusion_depth, dec_layers):
    parts = []
    parts.append("fusion%s" % ("default" if fusion_depth is None else fusion_depth))
    parts.append("dec%s" % ("default" if dec_layers is None else dec_layers))
    return "_".join(parts)


def train_argv(name):
    argv = [os.path.join("scripts", "ScanRefer_train.py"),
            "--tag", f"R33-{name.upper()}",
            "--seed", str(SEED),
            "--epoch", str(EPOCH),
            "--batch_size", str(BATCH_SIZE),
            "--parsing_folder", PARSING_FOLDER]
    if USE_CACHED_SCENES:
        argv += ["--use_cached_scenes", "--cached_scenes_root", CACHED_SCENES_ROOT]
    return argv + list(EXTRA_ARGS)


def newest_output_folder(before):
    output_root = os.path.join(REPO_ROOT, "outputs")
    if not os.path.isdir(output_root):
        return None
    after = {name for name in os.listdir(output_root)
             if os.path.isdir(os.path.join(output_root, name))}
    fresh = sorted(after - before)
    return fresh[-1] if fresh else None


def self_test():
    import argparse

    sys.path.insert(0, REPO_ROOT)
    import torch
    import models.match_module as match_module

    print("SELF_TEST -- MatchModule at each swept depth (CPU, no training)\n")
    args = argparse.Namespace()
    header = f"  {'depth':>6} {'self_attn':>10} {'cross_attn':>11} {'params':>14}"
    print(header)
    print("  " + "-" * (len(header) - 2))

    previous = None
    for depth in sorted({d for d, _ in ARMS if d is not None}):
        torch.manual_seed(0)
        module = match_module.MatchModule(args, num_proposals=256, det_channel=288,
                                          depth=depth)
        total = sum(p.numel() for p in module.parameters())
        print(f"  {depth:>6} {len(module.self_attn):>10} "
              f"{len(module.cross_attn):>11} {total:>14,}")
        if previous is not None and total <= previous:
            print("\n  FAIL: parameter count did not grow with depth; the patch is not "
                  "reaching the constructor.")
            return 1
        previous = total

    print("\n  OK: depth reaches the constructor and resizes every attention stack.")
    print("  The launcher applies this same override before the training script runs.")
    return 0


def _cli_guard():
    if len(sys.argv) <= 1:
        return False
    print(__doc__)
    print("This runner takes no command-line arguments. Edit the CONFIG block in")
    print(f"    {os.path.abspath(__file__)}")
    print("\nCurrent configuration:")
    for key, value in sorted(globals().items()):
        if key.isupper() and not key.startswith("_") and key != "LAUNCHER_TEMPLATE":
            print(f"    {key} = {value!r}")
    return True


def main():
    if _cli_guard():
        return 0
    if SELF_TEST:
        return self_test()
    if not RUN:
        print("RUN = False in this file; nothing to do.")
        return 0

    out_root = os.path.join(REPO_ROOT, OUT_ROOT)
    os.makedirs(out_root, exist_ok=True)

    print("=" * 84)
    print("R3.3 attention-layer sweep -- GPU. Each arm is a full training run.")
    print("=" * 84)
    print(f"arms: {len(ARMS)}   protocol: "
          f"{'cached (frozen detector)' if USE_CACHED_SCENES else 'end-to-end'}")
    print("NOTE: scripts/ScanRefer_train.py overrides --tag, --epoch and --batch_size")
    print("      in its debug block; folders are renamed after each arm instead.\n")

    results, failures = [], []
    for index, (fusion_depth, dec_layers) in enumerate(ARMS, 1):
        name = arm_name(fusion_depth, dec_layers)
        arm_dir = os.path.join(out_root, name)
        os.makedirs(arm_dir, exist_ok=True)

        launcher = os.path.join(arm_dir, "launch_train.py")
        with open(launcher, "w") as handle:
            handle.write(LAUNCHER_TEMPLATE.format(
                repo=REPO_ROOT, fusion_depth=fusion_depth, dec_layers=dec_layers,
                heads=FUSION_HEADS, argv=train_argv(name)))

        print(f"\n[{index}/{len(ARMS)}] {name}")
        print(f"        launcher: {os.path.relpath(launcher, REPO_ROOT)}")

        output_root = os.path.join(REPO_ROOT, "outputs")
        before = {entry for entry in os.listdir(output_root)
                  if os.path.isdir(os.path.join(output_root, entry))} \
            if os.path.isdir(output_root) else set()

        started = time.time()
        code = subprocess.call([sys.executable, launcher], cwd=REPO_ROOT)
        elapsed = time.time() - started

        record = {"arm": name, "fusion_depth": fusion_depth, "dec_layers": dec_layers,
                  "exit_code": code, "minutes": round(elapsed / 60, 1),
                  "folder": None, "eval_exit_code": None}

        if code != 0:
            failures.append((name, code))
            results.append(record)
            print(f"[sweep] {name} exited with code {code}")
            if STOP_ON_FAILURE:
                break
            continue

        produced = newest_output_folder(before)
        if produced:
            renamed = f"{produced}-R33-{name.upper()}"
            try:
                os.rename(os.path.join(output_root, produced),
                          os.path.join(output_root, renamed))
                produced = renamed
            except OSError as error:
                print(f"[sweep] could not rename {produced}: {error}")
            record["folder"] = produced
            print(f"[sweep] outputs/{produced}")

        if RUN_EVAL and record["folder"]:
            evaluation = [sys.executable, os.path.join("scripts", "ScanRefer_eval.py"),
                          "--folder", record["folder"], "--reference", "--force",
                          "--lang_num_max", "1"] + list(EXTRA_ARGS)
            print("[sweep] " + " ".join(evaluation))
            record["eval_exit_code"] = subprocess.call(evaluation, cwd=REPO_ROOT)

        results.append(record)

    summary = os.path.join(out_root, "sweep_summary.json")
    with open(summary, "w") as handle:
        json.dump({"arms": results, "seed": SEED,
                   "parsing_folder": PARSING_FOLDER,
                   "cached_scenes": USE_CACHED_SCENES}, handle, indent=2)

    print("\n" + "=" * 84)
    for record in results:
        print(f"  {record['arm']:<24} exit {record['exit_code']}  "
              f"{record['minutes']:>6.1f} min  {record['folder'] or '-'}")
    print(f"\nwrote {os.path.relpath(summary, REPO_ROOT)}")
    print("Read iou_rate_0.25 / iou_rate_0.5 from each arm's folder and report the")
    print("sweep as the justification R3.3 asks for. If one arm is within noise of the")
    print("published setting, say that too -- a flat curve still answers the comment.")

    if failures:
        print("\nfailed arms: " + ", ".join(f"{n} (code {c})" for n, c in failures))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
